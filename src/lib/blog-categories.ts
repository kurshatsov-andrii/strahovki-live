export function getCategory(slug: string): BlogCategory | undefined {
  return BLOG_CATEGORIES.find((c) => c.slug === slug);
}

export function categorizePost(post: { title: string; content: string }): BlogCategory | undefined {
  let best: BlogCategory | undefined;
  let bestScore = 0;
  for (const cat of BLOG_CATEGORIES) {
    let score = 0;
    for (const re of cat.keywords) {
      if (re.test(post.title)) score += 5;
      const g = new RegExp(re.source, "gi");
      score += Math.min((post.content.match(g) ?? []).length, 10);
    }
    if (score > bestScore) {
      bestScore = score;
      best = cat;
    }
  }
  return best;
}
