export const ukraineRegionOptions = ukraineRegions.map((r) => ({
  value: r.value,
  label: r.label,
}));

export function citiesForRegion(region: string): { value: string; label: string }[] {
  const found = ukraineRegions.find((r) => r.value === region);
  if (!found) return [];
  return found.cities
    .slice()
    .sort((a, b) => a.localeCompare(b, "uk"))
    .map((c) => ({ value: c, label: c }));
}

/** Обласний центр (перше місто у списку) — використовується як значення за замовчуванням. */
export function defaultCityForRegion(region: string): string {
  return ukraineRegions.find((r) => r.value === region)?.cities[0] ?? "";
}
