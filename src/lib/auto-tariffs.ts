export function autoAnnualPayment(
  vehicle: string,
  zone: AutoZone,
  age: number,
  privilege: string,
): number | null {
  const band = autoAgeBand(age);
  const idx = zoneIndex[zone];
  if (idx === undefined) return null;
  const usePrivileged = privilege && privilege !== "none";
  const row = (usePrivileged ? privileged[band][vehicle] : undefined) ?? standard[band][vehicle];
  const value = row?.[idx];
  return typeof value === "number" ? value : null;
}

