/** Області, для яких у таблиці МТСБУ вказано «вся область». */
const regionZones: Record<string, AutoZone> = {
  ternopilska: "5.4",
  lvivska: "5.3",
};

export function autoZoneForCity(city: string, region: string): AutoZone {
  const direct = cityZones[city.trim().toLowerCase()];
  if (direct) return direct;
  return regionZones[region] ?? "5.5";
}

export const autoZoneLabel = (zone: AutoZone) =>
  zone === "6" ? "Зона 6 (закордонна реєстрація)" : `Зона ${zone}`;

export type AutoAgeBand = "u23" | "a24_39" | "a40";

export function autoAgeBand(age: number): AutoAgeBand {
  if (age <= 23) return "u23";
  if (age <= 39) return "a24_39";
  return "a40";
}

